class TestPasswordHashing:
    """Regression tests for the passlib -> bcrypt migration.

    `passlib==1.7.4` read `bcrypt.__about__.__version__`, removed in bcrypt 4.1.
    On bcrypt 5.x that detection failed and every hash/verify raised
    `ValueError: password cannot be longer than 72 bytes`, so a fresh install
    had entirely broken auth while a pinned-old local venv looked healthy.
    """

    def test_round_trip(self):
        hashed = hash_password("correct horse battery staple")
        assert verify_password("correct horse battery staple", hashed) is True
        assert verify_password("wrong password", hashed) is False

    def test_produces_standard_bcrypt_format(self):
        """Must stay `$2b$` so hashes written by the passlib version still verify."""
        assert hash_password("whatever").startswith("$2b$")

    def test_verifies_a_hash_created_by_passlib(self):
        """Real hash of "password123", generated by passlib 1.7.4 + bcrypt 4.0.1.

        Existing users' stored hashes must keep working after the switch.
        """
        legacy = "$2b$12$Zm2YaSr7Z0gDFJE.T/lRBeZSCaj81wzV3SWhl7UH07v/6BD17jPJK"
        assert verify_password("password123", legacy) is True
        assert verify_password("not the password", legacy) is False

    def test_matches_passlib_truncation_for_long_passwords(self):
        """Real passlib hash of "a" * 200.

        passlib fed bcrypt only the first 72 bytes, so both the full password
        and its 72-byte prefix verified against it. Our explicit truncation has
        to reproduce that, or long-password users would be locked out.
        """
        legacy_long = "$2b$12$vzsIgCLAa77.Px5wS5ADZ.t3dKRzVGli1aSnWN3hlZBy5N2Oi3zgK"
        assert verify_password("a" * 200, legacy_long) is True
        assert verify_password("a" * 72, legacy_long) is True
        assert verify_password("b" * 200, legacy_long) is False

    def test_password_longer_than_72_bytes_does_not_raise(self):
        """The exact failure: bcrypt 5 raises above 72 bytes instead of truncating."""
        long_password = "a" * 200
        hashed = hash_password(long_password)
        assert verify_password(long_password, hashed) is True

    def test_multibyte_password(self):
        """Truncation is by bytes, so a multi-byte password must not split a char
        in a way that breaks encoding."""
        pw = "パスワード" * 20  # 3 bytes per char, well over the 72-byte limit
        hashed = hash_password(pw)
        assert verify_password(pw, hashed) is True

    def test_malformed_stored_hash_returns_false_not_error(self):
        assert verify_password("anything", "not-a-bcrypt-hash") is False
        assert verify_password("anything", "") is False

    def test_same_password_hashes_differently(self):
        """Salted, so two hashes of one password must differ."""
        assert hash_password("same") != hash_password("same")
